// Optional release signing: create android-vr-player/keystore.properties with
// storeFile, storePassword, keyAlias, keyPassword (never commit it). Without it the
// release APK is signed with the local debug key so it still installs.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

